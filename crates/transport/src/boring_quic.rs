//! Client-only BoringSSL TLS 1.3 provider for quinn 0.11.
//!
//! The TLS/QUIC bridge follows quinn-boring's design, but callbacks own separate mutex
//! state rather than aliasing the session while BoringSSL is borrowing it. Packet protection
//! uses ring's audited RFC 9001 primitives; all TLS messages come from BoringSSL.

