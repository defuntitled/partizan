/// Browser packet dimensions; Chrome's IETF QUIC packets have 8-byte destination IDs.
pub const INITIAL_MTU: u16 = 1250;
/// Connection IDs sent by the browser are empty; the random destination ID is 8 bytes.
pub const DESTINATION_CID_LEN: usize = 8;

/// Chrome 139 fresh-session QUIC profile (the reference capture also has optional PSK/0-RTT).
pub const PROFILE_NAME: &str = "Chrome 139, QUIC v1, fresh session";
/// TLS signature preferences from Chrome's QUIC stack, including the legacy SHA1 preference.
pub const SIGNATURE_ALGORITHMS: &str = "ecdsa_secp256r1_sha256:rsa_pss_rsae_sha256:rsa_pkcs1_sha256:\
    ecdsa_secp384r1_sha384:rsa_pss_rsae_sha384:rsa_pkcs1_sha384:rsa_pss_rsae_sha512:rsa_pkcs1_sha512:rsa_pkcs1_sha1";

type Shared = Arc<Mutex<Handshake>>;
static STATE: OnceLock<Index<Ssl, Shared>> = OnceLock::new();

fn index() -> Index<Ssl, Shared> {
    *STATE.get_or_init(|| Ssl::new_ex_index().expect("BoringSSL ex-data index"))
}

struct Config {
    context: SslContext,
    verification: ServerVerification,
}

/// A QUIC client endpoint whose TLS handshake is generated by BoringSSL.
pub fn client_endpoint(
    bind: SocketAddr,
    verification: ServerVerification,
    config: &QuicConfig,
) -> io::Result<quinn::Endpoint> {
    let mut builder = SslContextBuilder::new(SslMethod::tls()).map_err(io::Error::other)?;
    builder
        .set_min_proto_version(Some(SslVersion::TLS1_3))
        .map_err(io::Error::other)?;
    builder
        .set_max_proto_version(Some(SslVersion::TLS1_3))
        .map_err(io::Error::other)?;
    builder
        .set_cipher_list(PROFILE.cipher_list)
        .map_err(io::Error::other)?;
    builder
        .set_curves_list(PROFILE.curves)
        .map_err(io::Error::other)?;
    builder
        .set_sigalgs_list(SIGNATURE_ALGORITHMS)
        .map_err(io::Error::other)?;
    // QUIC's Chrome ClientHello has no TLS GREASE ciphers or extension; QUIC TPs do GREASE.
    builder.set_grease_enabled(false);
    builder.set_permute_extensions(true);
    builder
        .add_certificate_compression_algorithm(Brotli)
        .map_err(io::Error::other)?;
    builder
        .set_alpn_protos(b"\x02h3")
        .map_err(io::Error::other)?;
    // SAFETY: the callback table has static lifetime and callbacks only access SSL ex-data.
    if unsafe { ffi::SSL_CTX_set_quic_method(builder.as_ptr(), &METHOD) } != 1 {
        return Err(io::Error::other("cannot configure QUIC TLS"));
    }
    // No session cache and no 0-RTT, even if a caller reuses this endpoint.
    builder.set_session_cache_mode(boring::ssl::SslSessionCacheMode::OFF);
    let crypto = Config {
        context: builder.build(),
        verification,
    };
    let mut transport = config.transport_config();
    transport.initial_mtu(INITIAL_MTU);
    transport
        .stream_receive_window(quinn::VarInt::from_u32(6 << 20))
        .receive_window(quinn::VarInt::from_u32(15 << 20))
        .max_concurrent_bidi_streams(quinn::VarInt::from_u32(100))
        .max_concurrent_uni_streams(quinn::VarInt::from_u32(103));
    let mut client = quinn::ClientConfig::new(Arc::new(crypto));
    client.transport_config(Arc::new(transport));
    client.initial_dst_cid_provider(Arc::new(|| {
        let mut cid = [0; DESTINATION_CID_LEN];
        boring::rand::rand_bytes(&mut cid).expect("secure connection ID");
        ConnectionId::new(&cid)
    }));
    let mut endpoint_config = quinn::EndpointConfig::default();
    endpoint_config.supported_versions(vec![1]);
    endpoint_config
        .max_udp_payload_size(1472)
        .map_err(io::Error::other)?;
    endpoint_config.grease_quic_bit(false);
    endpoint_config.cid_generator(|| Box::new(quinn_proto::RandomConnectionIdGenerator::new(0)));
    let mut endpoint = quinn::Endpoint::new(
        endpoint_config,
        None,
        UdpSocket::bind(bind)?,
        Arc::new(quinn::TokioRuntime),
    )?;
    endpoint.set_default_client_config(client);
    Ok(endpoint)
}

impl crypto::ClientConfig for Config {
    fn start_session(
        self: Arc<Self>,
        version: u32,
        server_name: &str,
        params: &TransportParameters,
    ) -> Result<Box<dyn crypto::Session>, ConnectError> {
        if version != 1 {
            return Err(ConnectError::UnsupportedVersion);
        }
        let mut ssl = Ssl::new(&self.context).map_err(|_| ConnectError::EndpointStopping)?;
        ssl.set_hostname(server_name)
            .map_err(|_| ConnectError::InvalidServerName(server_name.into()))?;
        let server_name = server_name.to_owned();
        let verification = self.verification;
        ssl.set_custom_verify_callback(boring::ssl::SslVerifyMode::PEER, move |ssl| {
            let chain: Vec<Vec<u8>> = ssl
                .peer_cert_chain()
                .map(|chain| chain.iter().filter_map(|cert| cert.to_der().ok()).collect())
                .unwrap_or_default();
            verify(&chain, &server_name, verification).map_err(|_| {
                boring::ssl::SslVerifyError::Invalid(boring::ssl::SslAlert::BAD_CERTIFICATE)
            })
        });
        ssl.set_enable_ech_grease(true);
        let state = Arc::new(Mutex::new(Handshake::default()));
        ssl.set_ex_data(index(), state.clone());
        let wire = chrome_parameters(params);
        // SAFETY: ssl is live, BoringSSL copies the serialized parameters and disables early data.
        let ok = unsafe {
            ffi::SSL_set_connect_state(ssl.as_ptr());
            ffi::SSL_set_early_data_enabled(ssl.as_ptr(), 0);
            ffi::SSL_set_alps_use_new_codepoint(ssl.as_ptr(), 1);
            if ffi::SSL_add_application_settings(
                ssl.as_ptr(),
                b"h3".as_ptr(),
                2,
                std::ptr::null(),
                0,
            ) != 1
            {
                return Err(ConnectError::EndpointStopping);
            }
            ffi::SSL_set_quic_transport_params(ssl.as_ptr(), wire.as_ptr(), wire.len())
        };
        if ok != 1 {
            return Err(ConnectError::EndpointStopping);
        }
        let mut session = Session {
            ssl,
            state,
            write_level: 0,
            handshake_data_sent: false,
            next: None,
        };
        session
            .advance()
            .map_err(|_| ConnectError::EndpointStopping)?;
        Ok(Box::new(session))
    }
}

fn put_varint(value: u64, out: &mut Vec<u8>) {
    proto::varint::encode(value, out).expect("bounded profile value");
}

// Chrome uses the same shuffled TLV order as quiche's SerializeTransportParameters.
// Keep flow-control and stream limits identical to quinn's local configuration.
fn chrome_parameters(params: &TransportParameters) -> Vec<u8> {
    let mut encoded = Vec::new();
    params.write(&mut encoded);
    let mut fields = Vec::new();
    let mut cursor = encoded.as_slice();
    while !cursor.is_empty() {
        let (id, used) = proto::varint::decode(cursor).expect("quinn TP id");
        cursor = &cursor[used..];
        let (len, used) = proto::varint::decode(cursor).expect("quinn TP length");
        cursor = &cursor[used..];
        let len = len as usize;
        if matches!(id, 1 | 3..=9 | 15) {
            let value = if id == 1 {
                let (value, _) = proto::varint::decode(cursor).expect("quinn idle timeout");
                ((value as u32) | 0x80000000).to_be_bytes().to_vec()
            } else {
                cursor[..len].to_vec()
            };
            fields.push((id, value));
        }
        cursor = &cursor[len..];
    }
    let mut datagram = Vec::new();
    put_varint(65536, &mut datagram);
    fields.push((0x20, datagram));
    fields.push((0x4752, 1u32.to_be_bytes().to_vec()));
    let mut rtt = Vec::new();
    put_varint(100_000, &mut rtt);
    fields.push((0x3127, rtt));
    let mut random = [0; 32];
    boring::rand::rand_bytes(&mut random).expect("QUIC GREASE randomness");
    let grease_version =
        (u32::from_be_bytes(random[..4].try_into().expect("four bytes")) & 0xf0f0f0f0) | 0x0a0a0a0a;
    let mut version = Vec::from(1u32.to_be_bytes());
    if random[4] & 1 == 0 {
        version.extend_from_slice(&1u32.to_be_bytes());
        version.extend_from_slice(&grease_version.to_be_bytes());
    } else {
        version.extend_from_slice(&grease_version.to_be_bytes());
        version.extend_from_slice(&1u32.to_be_bytes());
    }
    fields.push((0x11, version));
    let grease_id = (u64::from_be_bytes(random[8..16].try_into().expect("eight bytes"))
        % ((1u64 << 62) - 31))
        / 31
        * 31
        + 27;
    fields.push((
        grease_id,
        random[16..16 + usize::from(random[5] % 16)].to_vec(),
    ));
    for i in (1..fields.len()).rev() {
        fields.swap(i, usize::from(random[i % 32]) % (i + 1));
    }
    let mut out = Vec::new();
    for (id, value) in fields {
        put_varint(id, &mut out);
        put_varint(value.len() as u64, &mut out);
        out.extend_from_slice(&value);
    }
    out
}

#[derive(Default)]
struct Handshake {
    outgoing: [Vec<u8>; 4],
    local: [Option<Secret>; 4],
    remote: [Option<Secret>; 4],
    alert: Option<u8>,
}

struct Secret {
    suite: u16,
    bytes: Zeroizing<Vec<u8>>,
}

struct Session {
    ssl: Ssl,
    state: Shared,
    write_level: usize,
    handshake_data_sent: bool,
    next: Option<(Secret, Secret)>,
}

impl Session {
    fn advance(&mut self) -> Result<(), TransportError> {
        // SAFETY: ssl is uniquely driven by this session; callbacks borrow independent ex-data.
        let result = unsafe {
            if ffi::SSL_is_init_finished(self.ssl.as_ptr()) == 1 {
                ffi::SSL_process_quic_post_handshake(self.ssl.as_ptr())
            } else {
                ffi::SSL_do_handshake(self.ssl.as_ptr())
            }
        };
        if let Some(alert) = self.state.lock().unwrap_or_else(|e| e.into_inner()).alert {
            return Err(TransportErrorCode::crypto(alert).into());
        }
        if result > 0 {
            return Ok(());
        }
        // SAFETY: the return code was produced by the immediately preceding operation on ssl.
        match unsafe { ffi::SSL_get_error(self.ssl.as_ptr(), result) } {
            ffi::SSL_ERROR_WANT_READ | ffi::SSL_ERROR_WANT_WRITE => Ok(()),
            _ => Err(TransportError {
                code: TransportErrorCode::crypto(40),
                frame: None,
                reason: boring::error::ErrorStack::get().to_string(),
            }),
        }
    }
}

impl crypto::Session for Session {
    fn initial_keys(&self, cid: &ConnectionId, side: Side) -> Keys {
        let prk = hkdf::Salt::new(
            hkdf::HKDF_SHA256,
            &[
                0x38, 0x76, 0x2c, 0xf7, 0xf5, 0x59, 0x34, 0xb3, 0x4d, 0x17, 0x9a, 0xe6, 0xa4, 0xc8,
                0x0c, 0xad, 0xcc, 0xbb, 0x7f, 0x0a,
            ],
        )
        .extract(cid);
        let client = Secret {
            suite: 0x1301,
            bytes: expand(&prk, b"client in", 32),
        };
        let server = Secret {
            suite: 0x1301,
            bytes: expand(&prk, b"server in", 32),
        };
        if side == Side::Client {
            keys(&client, &server)
        } else {
            keys(&server, &client)
        }
    }
    fn handshake_data(&self) -> Option<Box<dyn Any>> {
        self.ssl.selected_alpn_protocol().map(|protocol| {
            Box::new(crypto::rustls::HandshakeData {
                protocol: Some(protocol.to_vec()),
                server_name: None,
            }) as Box<dyn Any>
        })
    }
    fn peer_identity(&self) -> Option<Box<dyn Any>> {
        self.ssl.peer_cert_chain().map(|chain| {
            Box::new(
                chain
                    .iter()
                    .filter_map(|cert| cert.to_der().ok())
                    .map(rustls::pki_types::CertificateDer::from)
                    .collect::<Vec<_>>(),
            ) as Box<dyn Any>
        })
    }
    fn early_crypto(&self) -> Option<(Box<dyn crypto::HeaderKey>, Box<dyn crypto::PacketKey>)> {
        None
    }
    fn early_data_accepted(&self) -> Option<bool> {
        Some(false)
    }
    fn is_handshaking(&self) -> bool {
        // SAFETY: read-only query on this session's live SSL.
        unsafe { ffi::SSL_is_init_finished(self.ssl.as_ptr()) != 1 }
    }
    fn read_handshake(&mut self, bytes: &[u8]) -> Result<bool, TransportError> {
        // SAFETY: input is valid for its slice length; BoringSSL copies it. Level is TLS's current read level.
        let ok = unsafe {
            ffi::SSL_provide_quic_data(
                self.ssl.as_ptr(),
                ffi::SSL_quic_read_level(self.ssl.as_ptr()),
                bytes.as_ptr(),
                bytes.len(),
            )
        };
        if ok != 1 {
            return Err(TransportErrorCode::crypto(50).into());
        }
        self.advance()?;
        let available = !self.handshake_data_sent && self.handshake_data().is_some();
        self.handshake_data_sent |= available;
        Ok(available)
    }
    fn transport_parameters(&self) -> Result<Option<TransportParameters>, TransportError> {
        let mut data = std::ptr::null();
        let mut len = 0;
        // SAFETY: SSL owns the returned bytes for this immutable borrow; pointers are checked before slicing.
        unsafe {
            ffi::SSL_get_peer_quic_transport_params(self.ssl.as_ptr(), &mut data, &mut len);
        }
        if data.is_null() || len == 0 {
            return Ok(None);
        }
        if len > 65535 {
            return Err(TransportErrorCode::TRANSPORT_PARAMETER_ERROR.into());
        }
        // SAFETY: the API returns len initialized bytes owned by live ssl.
        TransportParameters::read(
            Side::Client,
            &mut Cursor::new(unsafe { std::slice::from_raw_parts(data, len) }),
        )
        .map(Some)
        .map_err(Into::into)
    }
    fn write_handshake(&mut self, out: &mut Vec<u8>) -> Option<Keys> {
        let mut state = self.state.lock().unwrap_or_else(|e| e.into_inner());
        out.append(&mut state.outgoing[self.write_level]);
        let next = if self.write_level == 0 {
            2
        } else if self.write_level == 2 {
            3
        } else {
            return None;
        };
        if state.local[next].is_none() || state.remote[next].is_none() {
            return None;
        }
        let local = state.local[next].take().expect("checked secret");
        let remote = state.remote[next].take().expect("checked secret");
        let result = keys(&local, &remote);
        self.write_level = next;
        if next == 3 {
            self.next = Some((local, remote));
        }
        Some(result)
    }
    fn next_1rtt_keys(&mut self) -> Option<KeyPair<Box<dyn crypto::PacketKey>>> {
        let (local, remote) = self.next.as_mut()?;
        local.bytes = local.expand(b"quic ku", local.bytes.len());
        remote.bytes = remote.expand(b"quic ku", remote.bytes.len());
        Some(KeyPair {
            local: Box::new(packet_key(local)),
            remote: Box::new(packet_key(remote)),
        })
    }
    fn is_valid_retry(&self, cid: &ConnectionId, header: &[u8], payload: &[u8]) -> bool {
        let mut pseudo = vec![cid.len() as u8];
        pseudo.extend_from_slice(cid);
        pseudo.extend_from_slice(header);
        let key = aead::LessSafeKey::new(
            aead::UnboundKey::new(
                &aead::AES_128_GCM,
                &[
                    0xbe, 0x0c, 0x69, 0x0b, 0x9f, 0x66, 0x57, 0x5a, 0x1d, 0x76, 0x6b, 0x54, 0xe3,
                    0x68, 0xc8, 0x4e,
                ],
            )
            .expect("RFC key"),
        );
        let mut tag = payload.to_vec();
        key.open_in_place(
            aead::Nonce::assume_unique_for_key([
                0x46, 0x15, 0x99, 0xd3, 0x5d, 0x63, 0x2b, 0xf2, 0x23, 0x98, 0x25, 0xbb,
            ]),
            aead::Aad::from(pseudo),
            &mut tag,
        )
        .is_ok()
    }
    fn export_keying_material(
        &self,
        output: &mut [u8],
        label: &[u8],
        context: &[u8],
    ) -> Result<(), crypto::ExportKeyingMaterialError> {
        // SAFETY: SSL owns exporter state; all input/output slices are valid for the supplied lengths.
        if unsafe {
            ffi::SSL_export_keying_material(
                self.ssl.as_ptr(),
                output.as_mut_ptr(),
                output.len(),
                label.as_ptr().cast(),
                label.len(),
                context.as_ptr(),
                context.len(),
                1,
            )
        } == 1
        {
            Ok(())
        } else {
            Err(crypto::ExportKeyingMaterialError)
        }
    }
}

static METHOD: ffi::SSL_QUIC_METHOD = ffi::SSL_QUIC_METHOD {
    set_read_secret: Some(read_secret),
    set_write_secret: Some(write_secret),
    add_handshake_data: Some(add_data),
    flush_flight: Some(flush),
    send_alert: Some(alert),
};

fn shared(ssl: *mut ffi::SSL) -> Shared {
    // SAFETY: only called by BoringSSL with a live SSL whose ex-data we installed before driving it.
    unsafe { SslRef::from_ptr(ssl) }
        .ex_data(index())
        .expect("QUIC state installed")
        .clone()
}

unsafe extern "C" fn read_secret(
    ssl: *mut ffi::SSL,
    level: ffi::ssl_encryption_level_t,
    cipher: *const ffi::SSL_CIPHER,
    secret: *const u8,
    len: usize,
) -> c_int {
    // SAFETY: forwards exactly the callback-provided pointers and lengths to the shared checker.
    unsafe { set_secret(ssl, level, cipher, secret, len, false) }
}
unsafe extern "C" fn write_secret(
    ssl: *mut ffi::SSL,
    level: ffi::ssl_encryption_level_t,
    cipher: *const ffi::SSL_CIPHER,
    secret: *const u8,
    len: usize,
) -> c_int {
    // SAFETY: forwards exactly the callback-provided pointers and lengths to the shared checker.
    unsafe { set_secret(ssl, level, cipher, secret, len, true) }
}
unsafe fn set_secret(
    ssl: *mut ffi::SSL,
    level: ffi::ssl_encryption_level_t,
    cipher: *const ffi::SSL_CIPHER,
    secret: *const u8,
    len: usize,
    local: bool,
) -> c_int {
    let level = level.0 as usize;
    if level >= 4 || level == 1 || cipher.is_null() || secret.is_null() || !matches!(len, 32 | 48) {
        return 0;
    }
    // SAFETY: BoringSSL supplies a valid cipher pointer and initialized secret slice.
    let suite = unsafe { ffi::SSL_CIPHER_get_protocol_id(cipher) };
    if !matches!(suite, 0x1301..=0x1303) {
        return 0;
    }
    // SAFETY: bounded initialized secret length supplied by BoringSSL.
    let bytes = Zeroizing::new(unsafe { std::slice::from_raw_parts(secret, len) }.to_vec());
    let shared = shared(ssl);
    let mut state = shared.lock().unwrap_or_else(|e| e.into_inner());
    if local {
        state.local[level] = Some(Secret { suite, bytes });
    } else {
        state.remote[level] = Some(Secret { suite, bytes });
    }
    1
}
unsafe extern "C" fn add_data(
    ssl: *mut ffi::SSL,
    level: ffi::ssl_encryption_level_t,
    data: *const u8,
    len: usize,
) -> c_int {
    let level = level.0 as usize;
    if level >= 4 || data.is_null() || len > 65535 {
        return 0;
    }
    let shared = shared(ssl);
    let mut state = shared.lock().unwrap_or_else(|e| e.into_inner());
    if state.outgoing[level].len() + len > 65535 {
        return 0;
    }
    // SAFETY: BoringSSL supplies len initialized message bytes; their copy is bounded above.
    state.outgoing[level].extend_from_slice(unsafe { std::slice::from_raw_parts(data, len) });
    1
}
unsafe extern "C" fn flush(_: *mut ffi::SSL) -> c_int {
    1
}
unsafe extern "C" fn alert(ssl: *mut ffi::SSL, _: ffi::ssl_encryption_level_t, alert: u8) -> c_int {
    shared(ssl).lock().unwrap_or_else(|e| e.into_inner()).alert = Some(alert);
    1
}

struct Len(usize);
impl hkdf::KeyType for Len {
    fn len(&self) -> usize {
        self.0
    }
}
fn expand(prk: &hkdf::Prk, label: &[u8], len: usize) -> Zeroizing<Vec<u8>> {
    let mut info = (len as u16).to_be_bytes().to_vec();
    info.push((6 + label.len()) as u8);
    info.extend_from_slice(b"tls13 ");
    info.extend_from_slice(label);
    info.push(0);
    let mut out = Zeroizing::new(vec![0; len]);
    prk.expand(&[&info], Len(len))
        .expect("bounded HKDF output")
        .fill(&mut out)
        .expect("HKDF output size");
    out
}
impl Secret {
    fn expand(&self, label: &[u8], len: usize) -> Zeroizing<Vec<u8>> {
        expand(
            &hkdf::Prk::new_less_safe(
                if self.suite == 0x1302 {
                    hkdf::HKDF_SHA384
                } else {
                    hkdf::HKDF_SHA256
                },
                &self.bytes,
            ),
            label,
            len,
        )
    }
    fn aead(&self) -> &'static aead::Algorithm {
        match self.suite {
            0x1301 => &aead::AES_128_GCM,
            0x1302 => &aead::AES_256_GCM,
            _ => &aead::CHACHA20_POLY1305,
        }
    }
}
fn keys(local: &Secret, remote: &Secret) -> Keys {
    Keys {
        header: KeyPair {
            local: Box::new(header_key(local)),
            remote: Box::new(header_key(remote)),
        },
        packet: KeyPair {
            local: Box::new(packet_key(local)),
            remote: Box::new(packet_key(remote)),
        },
    }
}
fn header_key(secret: &Secret) -> HeaderKey {
    let algorithm = match secret.suite {
        0x1301 => &aead::quic::AES_128,
        0x1302 => &aead::quic::AES_256,
        _ => &aead::quic::CHACHA20,
    };
    HeaderKey(
        aead::quic::HeaderProtectionKey::new(
            algorithm,
            &secret.expand(b"quic hp", algorithm.key_len()),
        )
        .expect("derived header key"),
    )
}
fn packet_key(secret: &Secret) -> PacketKey {
    let algorithm = secret.aead();
    PacketKey {
        key: aead::LessSafeKey::new(
            aead::UnboundKey::new(algorithm, &secret.expand(b"quic key", algorithm.key_len()))
                .expect("derived packet key"),
        ),
        iv: Zeroizing::new(
            secret
                .expand(b"quic iv", 12)
                .as_slice()
                .try_into()
                .expect("12-byte IV"),
        ),
        chacha: secret.suite == 0x1303,
    }
}
struct HeaderKey(aead::quic::HeaderProtectionKey);
impl HeaderKey {
    fn apply(&self, pn_offset: usize, packet: &mut [u8], decrypt: bool) {
        let mask = self
            .0
            .new_mask(&packet[pn_offset + 4..pn_offset + 20])
            .expect("QUIC sample size");
        let before = packet[0];
        packet[0] ^= mask[0] & if before & 0x80 == 0 { 0x1f } else { 0x0f };
        let len = usize::from((if decrypt { packet[0] } else { before }) & 3) + 1;
        for i in 0..len {
            packet[pn_offset + i] ^= mask[1 + i];
        }
    }
}
impl crypto::HeaderKey for HeaderKey {
    fn encrypt(&self, offset: usize, packet: &mut [u8]) {
        self.apply(offset, packet, false);
    }
    fn decrypt(&self, offset: usize, packet: &mut [u8]) {
        self.apply(offset, packet, true);
    }
    fn sample_size(&self) -> usize {
        16
    }
}
struct PacketKey {
    key: aead::LessSafeKey,
    iv: Zeroizing<[u8; 12]>,
    chacha: bool,
}
impl PacketKey {
    fn nonce(&self, packet: u64) -> aead::Nonce {
        let mut nonce = *self.iv;
        for (out, input) in nonce[4..].iter_mut().zip(packet.to_be_bytes()) {
            *out ^= input;
        }
        aead::Nonce::assume_unique_for_key(nonce)
    }
}
impl crypto::PacketKey for PacketKey {
    fn encrypt(&self, number: u64, bytes: &mut [u8], header_len: usize) {
        let (header, payload_tag) = bytes.split_at_mut(header_len);
        let (payload, tag) = payload_tag.split_at_mut(payload_tag.len() - 16);
        let value = self
            .key
            .seal_in_place_separate_tag(self.nonce(number), aead::Aad::from(header), payload)
            .expect("bounded QUIC packet");
        tag.copy_from_slice(value.as_ref());
    }
    fn decrypt(
        &self,
        number: u64,
        header: &[u8],
        payload: &mut BytesMut,
    ) -> Result<(), crypto::CryptoError> {
        let len = self
            .key
            .open_in_place(self.nonce(number), aead::Aad::from(header), payload)
            .map_err(|_| crypto::CryptoError)?
            .len();
        payload.truncate(len);
        Ok(())
    }
    fn tag_len(&self) -> usize {
        16
    }
    fn confidentiality_limit(&self) -> u64 {
        if self.chacha { u64::MAX } else { 1 << 23 }
    }
    fn integrity_limit(&self) -> u64 {
        if self.chacha { 1 << 36 } else { 1 << 52 }
    }
}
